class XteOverlay(QWidget):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setFixedHeight(55)  # Box height
        self.setAttribute(Qt.WA_TranslucentBackground)
        self.xte = 0.0 
        self.max_scale = 30.0  # It starts at maximum zoom
        self.cor_bombordo = QColor(220, 53, 69, 200)      # Red
        self.cor_boreste = QColor(40, 167, 69, 200)       # Green
        self.cor_destaque = QColor(255, 193, 7, 230)      # Yellow
        self.cor_fundo = QColor(25, 35, 55, 220)          # Dark blue
        self.cor_texto = QColor(255, 255, 255, 220)       # White text
        self.fonte = QFont("Segoe UI", 8)                 # Text source
        
    def set_xte(self, valor):
        """Dynamically updates the value and adjusts the ruler scale."""
        if valor is None:
            return
        self.xte = valor
        erro_absoluto = abs(valor)
        if erro_absoluto <= 30:
            self.max_scale = 30.0   # Maximum zoom
        elif erro_absoluto <= 50:
            self.max_scale = 50.0   # Medium zoom
        elif erro_absoluto <= 100:
            self.max_scale = 100.0  # Minimum zoom
        else:
            self.max_scale = math.ceil(erro_absoluto / 50.0) * 50.0 
        self.update() 

    def paintEvent(self, event):
        painter = QPainter(self)
        painter.setRenderHint(QPainter.Antialiasing)
        w = self.width()
        h = self.height()
        if w <= 0 or h <= 0: return
        center_x = w / 2.0
        # Axis
        bar_y = (h / 2.0) + 3  
        # Background and Border
        painter.setBrush(QBrush(self.cor_fundo)) 
        painter.setPen(QPen(QColor(60, 80, 110, 150), 1))
        painter.drawRoundedRect(QRectF(1, 1, w-2, h-2), 6, 6)
        
        margem = 45 
        track_left = margem
        track_right = w - margem
        area_util = (track_right - track_left) / 2.0
        pixels_por_metro = area_util / self.max_scale
        # Bar Gradients
        grad_bom = QLinearGradient(track_left, 0, center_x, 0)
        grad_bom.setColorAt(0.0, QColor(130, 30, 40, 200))
        grad_bom.setColorAt(1.0, QColor(230, 50, 65, 255))
        painter.setBrush(QBrush(grad_bom))
        painter.setPen(Qt.NoPen)
        painter.drawRoundedRect(QRectF(track_left, bar_y - 4, area_util, 8), 4, 4)
        
        grad_bor = QLinearGradient(center_x, 0, track_right, 0)
        grad_bor.setColorAt(0.0, QColor(40, 180, 70, 255))
        grad_bor.setColorAt(1.0, QColor(20, 110, 40, 200))
        painter.setBrush(QBrush(grad_bor))
        painter.drawRoundedRect(QRectF(center_x, bar_y - 4, area_util, 8), 4, 4)
        caneta_escala = QPen(QColor(255, 255, 255, 230), 1) # Text Thickness
        painter.setPen(caneta_escala) 
        fonte_escala = QFont("Segoe UI", 8, QFont.Bold)
        painter.setFont(fonte_escala)
        if self.max_scale <= 30:   passo = 10
        elif self.max_scale <= 50: passo = 10
        elif self.max_scale <= 100: passo = 25
        else:                      passo = 50
            
        qtd_marcas = int(self.max_scale / passo)

        for i in range(1, qtd_marcas + 1):
            dist = i * passo
            offset = dist * pixels_por_metro
            x_dir = center_x + offset 
            if x_dir <= track_right + 1:
                painter.drawLine(QPointF(x_dir, bar_y - 7), QPointF(x_dir, bar_y + 7))
                painter.drawText(QRectF(x_dir - 15, bar_y + 7, 30, 15), Qt.AlignCenter, f"{dist}")
            x_esq = center_x - offset 
            if x_esq >= track_left - 1:
                painter.drawLine(QPointF(x_esq, bar_y - 7), QPointF(x_esq, bar_y + 7))
                painter.drawText(QRectF(x_esq - 15, bar_y + 7, 30, 15), Qt.AlignCenter, f"{dist}")
                
        # Zero Marker
        painter.setPen(QPen(QColor(255, 255, 255, 255), 2)) 
        painter.drawLine(QPointF(center_x, bar_y - 10), QPointF(center_x, bar_y + 10))
        painter.drawText(QRectF(center_x - 10, bar_y + 8, 20, 15), Qt.AlignCenter, "0")
        
        # Indicator
        xte_visual = max(-self.max_scale, min(self.max_scale, self.xte)) 
        agulha_x = center_x + (xte_visual * pixels_por_metro)
        lado = "BOR" if self.xte > 0 else "BOM" if self.xte < 0 else ""
        texto = f"{abs(self.xte):.1f}{lado}" 
        
        # Shadow
        sombra_offset = 2
        painter.setBrush(QBrush(QColor(0, 0, 0, 150)))
        painter.setPen(Qt.NoPen)
        triangulo_sombra = QPolygonF([
            QPointF(agulha_x + sombra_offset, bar_y - 2),
            QPointF(agulha_x - 5 + sombra_offset, bar_y - 12),
            QPointF(agulha_x + 5 + sombra_offset, bar_y - 12)])
        painter.drawPolygon(triangulo_sombra)
        painter.drawRoundedRect(QRectF(agulha_x - 30 + sombra_offset, bar_y - 28 + sombra_offset, 60, 16), 4, 4)

        # Indicator
        painter.setBrush(QBrush(QColor(20, 20, 25, 240))) 
        painter.setPen(QPen(self.cor_destaque, 1.5)) 
        painter.drawRoundedRect(QRectF(agulha_x - 30, bar_y - 28, 60, 16), 4, 4)
        painter.setPen(QPen(self.cor_destaque))
        painter.setFont(QFont("Segoe UI", 8, QFont.Bold))
        painter.drawText(QRectF(agulha_x - 30, bar_y - 28, 60, 16), Qt.AlignCenter, texto)
        painter.setBrush(QBrush(self.cor_destaque)) 
        painter.setPen(Qt.NoPen)
        triangulo = QPolygonF([
            QPointF(agulha_x, bar_y - 2),
            QPointF(agulha_x - 5, bar_y - 10),
            QPointF(agulha_x + 5, bar_y - 10)])
        painter.drawPolygon(triangulo)
        painter.end()

