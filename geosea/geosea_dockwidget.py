    def action_next_head(self):
        """Advance to the next vertex in the sequence."""
        if not self.navigation_active:
            self.start_navigation()
            return
        # Next vertex
        next_index = self.current_vertex_index + 1
        if next_index >= len(self.vertex_sequence):
            # End of route 
            self.navigation_active = False
            if hasattr(self, 'target_vertex_marker') and self.target_vertex_marker:
                try: # Removes the marker
                    self.iface.mapCanvas().scene().removeItem(self.target_vertex_marker)
                    self.target_vertex_marker = None
                except:
                    pass
            if hasattr(self, 'btn_startnav'):
                self.btn_startnav.setText("▶ START NAVIGATION")
