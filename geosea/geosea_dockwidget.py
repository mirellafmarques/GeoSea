class CompassOverlay(QWidget):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.course = 0.0         
        self.size = 50  
        self.cor_fundo = QColor(255, 255, 255, 200)      # Fundo Branco (200 = semi-transparente)
        self.cor_borda = QColor(150, 150, 150, 150)      # Borda Cinza
        self.cor_proa = QColor(231, 76, 60)              # Triângulo Vermelho
        self.cor_texto_n = QColor(44, 62, 80)            # Letra "N" (Chumbo Escuro)
        self.cor_texto_graus = QColor(44, 62, 80)        # Números Centrais (Chumbo Escuro)
        self.fonte_estilo = "Arial"
        self.setFixedSize(self.size + 20, self.size + 20)
        self.setAttribute(Qt.WA_TranslucentBackground)
        self.setStyleSheet("background: transparent;")
        
    def set_course(self, course):
        self.course = course % 360
        self.update()
        
    def paintEvent(self, event):
        painter = QPainter(self)
        painter.setRenderHint(QPainter.Antialiasing)
        
        center_x = self.width() // 2
        center_y = self.height() // 2
        radius = self.size // 2
        
        painter.setPen(QPen(self.cor_borda, 2))  
        painter.setBrush(QBrush(self.cor_fundo))
        painter.drawEllipse(center_x - radius, center_y - radius, radius * 2, radius * 2)
        
        # Fixed Bow Bearing
        painter.setPen(Qt.NoPen)
        painter.setBrush(QBrush(self.cor_proa))
        tamanho_triangulo = radius * 0.22 
        marca_barco = QPolygonF([
            QPointF(center_x, center_y - radius - tamanho_triangulo), 
            QPointF(center_x - tamanho_triangulo*1.5, center_y - radius + tamanho_triangulo), 
            QPointF(center_x + tamanho_triangulo*1.5, center_y - radius + tamanho_triangulo)])
        painter.drawPolygon(marca_barco)
        
        painter.save()
        painter.translate(center_x, center_y)
        painter.rotate(-self.course) # Turn "North" in the opposite direction
        altura_caixa = int(radius * 0.8)
        painter.restore()
        # Compass rose (North rotating)
        painter.save()
        painter.translate(center_x, center_y)
        painter.rotate(-self.course)

        pen = QPen(self.cor_texto_n, 1.0) # Line thickness
        pen.setCapStyle(Qt.RoundCap)
        painter.setPen(pen)
        painter.setBrush(QBrush(self.cor_texto_n))

        r_maior = radius * 0.45
        r_menor = radius * 0.25

        for ang in [0, 90, 180, 270]:
            painter.save()
            painter.rotate(ang)
            ponta = QPolygonF([ QPointF(0, -r_maior), QPointF(-radius*0.06, -radius*0.20), QPointF(0, 0), QPointF(radius*0.06, -radius*0.20)  ])
            painter.drawPolygon(ponta)
            painter.restore()

        # Diagonal points (NE SE SW NW)
        for ang in [45, 135, 225, 315]:
            painter.save()
            painter.rotate(ang)
            ponta = QPolygonF([ QPointF(0, -r_menor), QPointF(-radius*0.045, -radius*0.15), QPointF(0, 0), QPointF(radius*0.045, -radius*0.15) ])
            painter.drawPolygon(ponta)
            painter.restore()

        painter.drawLine( QPointF(0, -r_maior*0.70), QPointF(0,  r_maior*0.70) ) # Cruz principal
        painter.drawLine( QPointF(-r_maior*0.70, 0), QPointF(r_maior*0.70, 0)  )

        diag = r_maior * 0.40 # Diagonal cross
        painter.drawLine( QPointF(-diag, -diag), QPointF(diag, diag) )
        painter.drawLine( QPointF(diag, -diag), QPointF(-diag, diag) )

        losango = QPolygonF([ QPointF(0, -radius*0.08), QPointF(radius*0.08, 0), QPointF(0, radius*0.08), QPointF(-radius*0.08, 0) ])
        painter.setBrush(QBrush(Qt.white))
        painter.drawPolygon(losango)
        
        fonte = QFont("Arial", int(radius*0.28)) # Letter N
        fonte.setBold(True)
        painter.setFont(fonte)
        painter.setPen(QPen(self.cor_texto_n))
        painter.drawText(QRectF(-radius, -radius*0.82, radius*2, radius*0.40), Qt.AlignCenter, "N")
        painter.restore()    

        # Bearing value below the compass
        tamanho_fonte = max(8, int(radius * 0.30))
        fonte = QFont(self.fonte_estilo, tamanho_fonte)
        fonte.setBold(True)
        painter.setFont(fonte)
        painter.setPen(QPen(self.cor_texto_graus))
        painter.drawText(
            QRectF( center_x - radius,
                center_y + radius + 1.0,      # distance below the compass
                radius * 2,
                radius * 0.50),
            Qt.AlignCenter,
            f"{self.course:03.0f}°")
        painter.end()
 

