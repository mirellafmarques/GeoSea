        """ Moves the selected line up (-1) or down (1)."""
        row = self.tableWidget.currentRow()
        column_count = self.tableWidget.columnCount()
        target = row + direcao
        if target < 0 or target >= self.tableWidget.rowCount() or row < 0:
            return
        self.tableWidget.blockSignals(True)
        for col in range(column_count):
            item_origem = self.tableWidget.takeItem(row, col)
